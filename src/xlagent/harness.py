def assemble_script(task_code: str, title: str) -> str:
    """Combine the model-written task code with the fixed header and harness."""
    safe_title = title.replace('"""', "'''").strip() or "Excel automation"
    return HEADER.format(title=safe_title) + "\n" + task_code.strip() + "\n" + FOOTER


def extract_task_code(script: str) -> str:
    """Return only the generated part of an assembled script (used by tests and the UI)."""
    body = script.split(HARNESS_MARKER, 1)[0]
    _, _, rest = body.partition('\n"""\n')  # end of the header docstring
    return rest.strip() + "\n"
